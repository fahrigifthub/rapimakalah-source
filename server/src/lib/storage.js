import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { config } from '../config.js';

function userDir(userId) {
  return path.join(config.storageDir, userId);
}

export async function ensureStorage() {
  await fs.mkdir(config.storageDir, { recursive: true });
}

export async function saveUpload(userId, buffer, extension = 'docx') {
  const dir = userDir(userId);
  await fs.mkdir(dir, { recursive: true });
  const storedName = `${crypto.randomUUID()}.${extension}`;
  await fs.writeFile(path.join(dir, storedName), buffer, { mode: 0o600 });
  return storedName;
}

export function resolveStoredPath(userId, storedName) {
  // Stored names are generated by RapiMakalah (UUID + extension, optionally .paperly.docx), never user input.
  if (typeof storedName !== 'string' || !/^[a-zA-Z0-9][a-zA-Z0-9._-]*\.docx$/.test(storedName) || storedName.includes('..')) {
    throw new Error('Nama penyimpanan tidak valid.');
  }
  const userBase = path.resolve(userDir(userId));
  const resolved = path.resolve(userBase, storedName);
  const base = path.resolve(config.storageDir);
  if (!resolved.startsWith(base + path.sep) || !resolved.startsWith(userBase + path.sep)) {
    throw new Error('Path di luar storage.');
  }
  return resolved;
}

export async function readStored(userId, storedName) {
  return fs.readFile(resolveStoredPath(userId, storedName));
}

export async function writeProcessed(userId, originalStoredName, buffer) {
  const dir = userDir(userId);
  await fs.mkdir(dir, { recursive: true });
  const base = originalStoredName.replace(/\.docx$/i, '');
  const storedName = `${base}.paperly.docx`;
  await fs.writeFile(path.join(dir, storedName), buffer, { mode: 0o600 });
  return storedName;
}

export async function deleteStored(userId, storedName) {
  if (!storedName) return;
  try {
    await fs.unlink(resolveStoredPath(userId, storedName));
  } catch (error) {
    if (error.code !== 'ENOENT') console.warn('[paperly] Gagal menghapus file:', error.message);
  }
}

export function downloadName(originalName, suffix = '') {
  const base = String(originalName || 'dokumen').replace(/\.docx$/i, '');
  return `${base}${suffix}.docx`;
}
